// retainTemplate is the deployed template with DeletionPolicy and UpdateReplacePolicy set to
// Retain on every converted resource, so deleting the stack leaves them in place.
func retainTemplate(t *cfn.Template, active []cfn.Resource) (string, error) {
	doc := map[string]any{}
	for k, v := range t.Raw {
		doc[k] = v
	}
	resources, _ := doc["Resources"].(map[string]any)
	out := map[string]any{}
	for id, r := range resources {
		out[id] = r
	}
	for _, r := range active {
		m, ok := out[r.LogicalID].(map[string]any)
		if !ok {
			continue
		}
		c := map[string]any{}
		for k, v := range m {
			c[k] = v
		}
		c["DeletionPolicy"] = "Retain"
		c["UpdateReplacePolicy"] = "Retain"
		out[r.LogicalID] = c
	}
	doc["Resources"] = out
	b, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return "", err
	}
	return string(b) + "\n", nil
}

func handover(in Input, imports int, addrs []string) string {
	var b strings.Builder
	stack := in.StackName
	fmt.Fprintf(&b, `# Handover: CloudFormation stack %q to Terraform

Generated by cfn2tf. %d resources, %d import blocks. Nothing is created, replaced or deleted
at any step; if a step shows otherwise, stop there.

## 1. Keep the resources when the stack goes

Update the stack with the same template plus DeletionPolicy and UpdateReplacePolicy Retain on
every resource. Only those two attributes change, so CloudFormation touches no resource.

    aws cloudformation update-stack --stack-name %s \
      --template-body file://retain-template.json%s%s
    aws cloudformation wait stack-update-complete --stack-name %s

## 2. Plan the import and check it is a pure import

    terraform init
    terraform plan -out handover.plan

The plan must say "%d to import, 0 to add, 0 to change, 0 to destroy". Anything else is a
difference between this code and what is deployed: fix the code (or the resource, through the
stack) and plan again. Do not apply a plan that changes anything.

## 3. Import

    terraform apply handover.plan
    terraform plan -detailed-exitcode    # exit code 0: no changes

## 4. Retire the stack

    aws cloudformation delete-stack --stack-name %s
    aws cloudformation wait stack-delete-complete --stack-name %s
    terraform plan -detailed-exitcode    # still exit code 0: every resource survived

Then delete imports.tf; the resources live in the Terraform state now.

## Rollback

Until step 4 nothing has moved: remove the Terraform state (terraform state rm on each address,
or delete the workspace) and the stack still owns everything. After step 4, the resources are
retained and owned by Terraform; to give them back, create a stack with resource import
(aws cloudformation create-change-set --change-set-type IMPORT).

## Resources

`, stack, len(addrs), imports, stack, paramArgs(in), capabilities(addrs), stack, imports, stack, stack)
	for _, a := range addrs {
		fmt.Fprintf(&b, "- `%s`\n", a)
	}
	return b.String()
}

func paramArgs(in Input) string {
	if len(in.Template.ParamOrder) == 0 {
		return ""
	}
	var parts []string
	for _, p := range in.Template.ParamOrder {
		parts = append(parts, "ParameterKey="+p+",UsePreviousValue=true")
	}
	return " \\\n      --parameters " + strings.Join(parts, " ")
}

func capabilities(addrs []string) string {
	for _, a := range addrs {
		if strings.HasPrefix(a, "aws_iam_") {
			return " \\\n      --capabilities CAPABILITY_NAMED_IAM"
		}
	}
	return ""
}
