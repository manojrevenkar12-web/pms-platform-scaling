// Package cfn2tf turns a deployed CloudFormation stack into Terraform that adopts the same
// resources: resource blocks that describe what exists, import blocks that bind them to their
// physical IDs, and a handover plan. Nothing is recreated.
//
// It converts what it understands exactly and refuses the rest: an unsupported resource type,
// property or intrinsic function is an error naming the logical ID, never a guess. Conditions,
// mappings and pseudo parameters are resolved with the values the stack was deployed with.
package cfn2tf

import (
	"errors"
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/manojrevenkar12-web/pms-platform-scaling/internal/cfn"
)

// Input is everything needed to convert one stack.
type Input struct {
	Template  *cfn.Template
	StackName string
	Region    string
	AccountID string
	Partition string            // default "aws"
	Params    map[string]string // deployed parameter values
	Physical  map[string]string // logical ID -> physical ID
}

// Output is the generated Terraform and the handover plan.
type Output struct {
	Files     map[string]string // file name -> content
	Imports   int
	Resources []string // Terraform addresses
}

// Unsupported collects everything the converter refused.
type Unsupported struct{ Problems []string }

func (u *Unsupported) Error() string {
	return fmt.Sprintf("cannot convert %d item(s):\n  - %s", len(u.Problems), strings.Join(u.Problems, "\n  - "))
}

type ref struct {
	addr   string            // e.g. aws_s3_bucket.exports
	ref    string            // attribute that Ref returns
	getAtt map[string]string // CloudFormation attribute -> Terraform attribute ("attr|suffix" adds a literal)
}

type conv struct {
	in       Input
	conds    map[string]bool
	refs     map[string]ref
	problems []string
	data     map[string]bool // data sources used
	vars     map[string]string
}

// noValue marks AWS::NoValue: the property is left out.
type noValue struct{}

// Convert converts the stack.
func Convert(in Input) (*Output, error) {
	if in.Partition == "" {
		in.Partition = "aws"
	}
	c := &conv{in: in, conds: map[string]bool{}, refs: map[string]ref{}, data: map[string]bool{}, vars: map[string]string{}}
	for _, name := range in.Template.ParamOrder {
		c.vars[name] = snake(name)
	}
	if err := c.evalConditions(); err != nil {
		return nil, err
	}
	// Pass 1: where each resource will live, so references work in any order.
	var active []cfn.Resource
	for _, r := range in.Template.Resources {
		if r.Condition != "" && !c.conds[r.Condition] {
			continue
		}
		m, ok := mappers[r.Type]
		if !ok {
			c.problems = append(c.problems, fmt.Sprintf("%s: resource type %s is not supported", r.LogicalID, r.Type))
			continue
		}
		if _, ok := in.Physical[r.LogicalID]; !ok && m.needsPhysical {
			c.problems = append(c.problems, fmt.Sprintf("%s: not in the stack's resources (was it deployed?)", r.LogicalID))
			continue
		}
		c.refs[r.LogicalID] = m.ref(snake(r.LogicalID))
		active = append(active, r)
	}
	// Pass 2: blocks.
	var blocks, imports []*Block
	var addrs []string
	for _, r := range active {
		m := mappers[r.Type]
		p := &props{c: c, r: r, where: r.LogicalID, m: r.Properties, used: map[string]bool{}}
		bs, ims := m.convert(c, p, snake(r.LogicalID))
		p.checkUnused()
		for _, b := range bs {
			if len(r.DependsOn) > 0 && b.Type == "resource" {
				var deps []Expr
				for _, d := range r.DependsOn {
					if dr, ok := c.refs[d]; ok {
						deps = append(deps, Raw(dr.addr))
					}
				}
				if len(deps) > 0 && b == bs[0] {
					b.Set("depends_on", deps)
				}
			}
			if b.Type == "resource" {
				addrs = append(addrs, b.Labels[0]+"."+b.Labels[1])
			}
		}
		blocks = append(blocks, bs...)
		imports = append(imports, ims...)
	}
	outputs := c.outputs()
	if len(c.problems) > 0 {
		return nil, &Unsupported{Problems: c.problems}
	}
	files := map[string]string{
		"main.tf":      header(in) + Render(blocks),
		"imports.tf":   "# Bind the resources above to what CloudFormation created. Remove after the first apply.\n\n" + Render(imports),
		"variables.tf": c.variables(),
		"outputs.tf":   Render(outputs),
		"versions.tf":  c.versions(),
		"HANDOVER.md":  handover(in, len(imports), addrs),
	}
	retain, err := retainTemplate(in.Template, active)
	if err != nil {
		return nil, err
	}
	files["retain-template.json"] = retain
	return &Output{Files: files, Imports: len(imports), Resources: addrs}, nil
}

func header(in Input) string {
	return fmt.Sprintf("# Generated by cfn2tf from CloudFormation stack %q. Review, then follow HANDOVER.md.\n\n", in.StackName)
}

func (c *conv) fail(format string, args ...any) {
	c.problems = append(c.problems, fmt.Sprintf(format, args...))
}

// snake turns LogicalIDs like ExportsBucketPolicy into exports_bucket_policy.
func snake(s string) string {
	var b strings.Builder
	rs := []rune(s)
	for i, r := range rs {
		if unicode.IsUpper(r) {
			if i > 0 && (unicode.IsLower(rs[i-1]) || unicode.IsDigit(rs[i-1]) || (i+1 < len(rs) && unicode.IsLower(rs[i+1]) && unicode.IsUpper(rs[i-1]))) {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(r))
		} else if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "r_" + out
	}
	return out
}

// ---- static evaluation (conditions, mappings, import IDs) ----

func (c *conv) evalConditions() error {
	names := make([]string, 0, len(c.in.Template.Conditions))
	for n := range c.in.Template.Conditions {
		names = append(names, n)
	}
	sort.Strings(names)
	var visiting = map[string]bool{}
	var eval func(string) (bool, error)
	eval = func(name string) (bool, error) {
		if v, ok := c.conds[name]; ok {
			return v, nil
		}
		def, ok := c.in.Template.Conditions[name]
		if !ok {
			return false, fmt.Errorf("unknown condition %s", name)
		}
		if visiting[name] {
			return false, fmt.Errorf("condition %s refers to itself", name)
		}
		visiting[name] = true
		v, err := c.static(def, eval)
		if err != nil {
			return false, fmt.Errorf("condition %s: %w", name, err)
		}
		b, ok := v.(bool)
		if !ok {
			return false, fmt.Errorf("condition %s is not a boolean", name)
		}
		c.conds[name] = b
		return b, nil
	}
	for _, n := range names {
		if _, err := eval(n); err != nil {
			return err
		}
	}
	return nil
}

func (c *conv) paramValue(name string) (any, bool) {
	p, ok := c.in.Template.Parameters[name]
	if !ok {
		return nil, false
	}
	v, ok := c.in.Params[name]
	if !ok {
		if p.Default == nil {
			return nil, false
		}
		v = fmt.Sprint(p.Default)
	}
	if strings.HasPrefix(p.Type, "List<") || p.Type == "CommaDelimitedList" {
		var out []any
		for _, s := range strings.Split(v, ",") {
			out = append(out, strings.TrimSpace(s))
		}
		return out, true
	}
	return v, true
}

func (c *conv) pseudo(name string) (any, bool) {
	switch name {
	case "AWS::Region":
		return c.in.Region, true
	case "AWS::AccountId":
		return c.in.AccountID, true
	case "AWS::Partition":
		return c.in.Partition, true
	case "AWS::URLSuffix":
		if strings.HasPrefix(c.in.Region, "cn-") {
			return "amazonaws.com.cn", true
		}
		return "amazonaws.com", true
	case "AWS::StackName":
		return c.in.StackName, true
	case "AWS::NoValue":
		return noValue{}, true
	}
	return nil, false
}

// static evaluates an expression to a plain value using deployed parameters, pseudo parameters,
// conditions, mappings and physical IDs. It cannot see resource attributes other than Ref.
func (c *conv) static(v any, cond func(string) (bool, error)) (any, error) {
	if cond == nil {
		cond = func(n string) (bool, error) {
			b, ok := c.conds[n]
			if !ok {
				return false, fmt.Errorf("unknown condition %s", n)
			}
			return b, nil
		}
	}
	switch x := v.(type) {
	case string, bool, int64, float64, nil:
		return x, nil
	case []any:
		out := make([]any, 0, len(x))
		for _, e := range x {
			s, err := c.static(e, cond)
			if err != nil {
				return nil, err
			}
			if _, skip := s.(noValue); !skip {
				out = append(out, s)
			}
		}
		return out, nil
	case map[string]any:
		if len(x) != 1 {
			out := map[string]any{}
			for k, e := range x {
				s, err := c.static(e, cond)
				if err != nil {
					return nil, err
				}
				out[k] = s
			}
			return out, nil
		}
		for fn, arg := range x {
			switch fn {
			case "Ref":
				name, _ := arg.(string)
				if v, ok := c.pseudo(name); ok {
					return v, nil
				}
				if v, ok := c.paramValue(name); ok {
					return v, nil
				}
				if id, ok := c.in.Physical[name]; ok {
					return id, nil
				}
				return nil, fmt.Errorf("Ref %s has no known value", name)
			case "Condition":
				name, _ := arg.(string)
				return cond(name)
			case "Fn::Equals", "Fn::And", "Fn::Or", "Fn::Not":
				list, _ := arg.([]any)
				vals := make([]any, len(list))
				for i, e := range list {
					s, err := c.static(e, cond)
					if err != nil {
						return nil, err
					}
					vals[i] = s
				}
				switch fn {
				case "Fn::Equals":
					if len(vals) != 2 {
						return nil, errors.New("Fn::Equals needs two values")
					}
					return fmt.Sprint(vals[0]) == fmt.Sprint(vals[1]), nil
				case "Fn::Not":
					b, ok := first(vals).(bool)
					if !ok {
						return nil, errors.New("Fn::Not needs a condition")
					}
					return !b, nil
				default:
					result := fn == "Fn::And"
					for _, e := range vals {
						b, ok := e.(bool)
						if !ok {
							return nil, fmt.Errorf("%s needs conditions", fn)
						}
						if fn == "Fn::And" {
							result = result && b
						} else {
							result = result || b
						}
					}
					return result, nil
				}
			case "Fn::If":
				list, _ := arg.([]any)
				if len(list) != 3 {
					return nil, errors.New("Fn::If needs [condition, then, else]")
				}
				name, _ := list[0].(string)
				b, err := cond(name)
				if err != nil {
					return nil, err
				}
				if b {
					return c.static(list[1], cond)
				}
				return c.static(list[2], cond)
			case "Fn::FindInMap":
				return c.findInMap(arg, cond)
			case "Fn::Join":
				list, _ := arg.([]any)
				if len(list) != 2 {
					return nil, errors.New("Fn::Join needs [delimiter, list]")
				}
				items, err := c.static(list[1], cond)
				if err != nil {
					return nil, err
				}
				parts, _ := items.([]any)
				ss := make([]string, len(parts))
				for i, p := range parts {
					ss[i] = fmt.Sprint(p)
				}
				return strings.Join(ss, fmt.Sprint(list[0])), nil
			case "Fn::Select":
				list, _ := arg.([]any)
				if len(list) != 2 {
					return nil, errors.New("Fn::Select needs [index, list]")
				}
				idx, err := c.static(list[0], cond)
				if err != nil {
					return nil, err
				}
				items, err := c.static(list[1], cond)
				if err != nil {
					return nil, err
				}
				i, err := strconv.Atoi(fmt.Sprint(idx))
				arr, _ := items.([]any)
				if err != nil || i < 0 || i >= len(arr) {
					return nil, errors.New("Fn::Select index out of range")
				}
				return arr[i], nil
			case "Fn::Sub":
				return c.staticSub(arg, cond)
			}
			return nil, fmt.Errorf("%s cannot be resolved without deploying", fn)
		}
	}
	return nil, fmt.Errorf("cannot resolve %T", v)
}

func first(v []any) any {
	if len(v) == 0 {
		return nil
	}
	return v[0]
}

func (c *conv) findInMap(arg any, cond func(string) (bool, error)) (any, error) {
	list, _ := arg.([]any)
	if len(list) != 3 {
		return nil, errors.New("Fn::FindInMap needs [map, key, key]")
	}
	keys := make([]string, 3)
	for i, e := range list {
		s, err := c.static(e, cond)
		if err != nil {
			return nil, err
		}
		keys[i] = fmt.Sprint(s)
	}
	m1, _ := c.in.Template.Mappings[keys[0]].(map[string]any)
	m2, _ := m1[keys[1]].(map[string]any)
	v, ok := m2[keys[2]]
	if !ok {
		return nil, fmt.Errorf("Fn::FindInMap %s/%s/%s not found", keys[0], keys[1], keys[2])
	}
	return v, nil
}

var subVar = regexp.MustCompile(`\$\{([^}]*)\}`)

func (c *conv) staticSub(arg any, cond func(string) (bool, error)) (any, error) {
	s, vars, err := subArgs(arg)
	if err != nil {
		return nil, err
	}
	var firstErr error
	out := subVar.ReplaceAllStringFunc(s, func(m string) string {
		name := m[2 : len(m)-1]
		if strings.HasPrefix(name, "!") {
			return "${" + name[1:] + "}"
		}
		var v any
		var err error
		if e, ok := vars[name]; ok {
			v, err = c.static(e, cond)
		} else if strings.Contains(name, ".") {
			err = fmt.Errorf("${%s} needs a deployed attribute", name)
		} else {
			v, err = c.static(map[string]any{"Ref": name}, cond)
		}
		if err != nil && firstErr == nil {
			firstErr = err
		}
		return fmt.Sprint(v)
	})
	return out, firstErr
}

func subArgs(arg any) (string, map[string]any, error) {
	switch x := arg.(type) {
	case string:
		return x, nil, nil
	case []any:
		if len(x) == 2 {
			s, ok1 := x[0].(string)
			m, ok2 := x[1].(map[string]any)
			if ok1 && ok2 {
				return s, m, nil
			}
		}
	}
	return "", nil, errors.New("Fn::Sub needs a string or [string, {vars}]")
}

// ---- conversion to Terraform expressions ----

// value converts a CloudFormation value into an HCL expression. where names the property for
// error messages.
func (c *conv) value(v any, where string) Expr {
	switch x := v.(type) {
	case nil:
		return nil
	case string, bool, int64, float64:
		return x
	case []any:
		out := []Expr{}
		for i, e := range x {
			ev := c.value(e, fmt.Sprintf("%s[%d]", where, i))
			if _, skip := ev.(noValue); skip || ev == nil {
				continue
			}
			out = append(out, ev)
		}
		return out
	case map[string]any:
		if len(x) == 1 {
			for fn, arg := range x {
				if fn == "Ref" || strings.HasPrefix(fn, "Fn::") || fn == "Condition" {
					return c.intrinsic(fn, arg, where)
				}
			}
		}
		o := NewObject()
		for k, e := range x {
			ev := c.value(e, where+"."+k)
			if _, skip := ev.(noValue); skip || ev == nil {
				continue
			}
			o.Set(k, ev)
		}
		return o.Sorted()
	}
	c.fail("%s: unsupported value %T", where, v)
	return nil
}

func (c *conv) intrinsic(fn string, arg any, where string) Expr {
	switch fn {
	case "Ref":
		name, _ := arg.(string)
		return c.refExpr(name, where)
	case "Fn::GetAtt":
		var res, attr string
		switch a := arg.(type) {
		case []any:
			if len(a) == 2 {
				res, _ = a[0].(string)
				attr, _ = a[1].(string)
			}
		case string:
			res, attr, _ = strings.Cut(a, ".")
		}
		return c.getAttExpr(res, attr, where)
	case "Fn::Sub":
		s, vars, err := subArgs(arg)
		if err != nil {
			c.fail("%s: %v", where, err)
			return nil
		}
		var t Template
		last := 0
		for _, m := range subVar.FindAllStringSubmatchIndex(s, -1) {
			if m[0] > last {
				t = append(t, s[last:m[0]])
			}
			name := s[m[2]:m[3]]
			switch {
			case strings.HasPrefix(name, "!"):
				t = append(t, "${"+name[1:]+"}")
			case vars[name] != nil:
				t = append(t, c.value(vars[name], where))
			case strings.Contains(name, "."):
				res, attr, _ := strings.Cut(name, ".")
				t = append(t, c.getAttExpr(res, attr, where))
			default:
				t = append(t, c.refExpr(name, where))
			}
			last = m[1]
		}
		if last < len(s) {
			t = append(t, s[last:])
		}
		return simplify(t)
	case "Fn::Join":
		list, _ := arg.([]any)
		if len(list) != 2 {
			c.fail("%s: Fn::Join needs [delimiter, list]", where)
			return nil
		}
		delim, _ := list[0].(string)
		items := c.value(list[1], where)
		parts, ok := items.([]Expr)
		if !ok {
			return Call{"join", []Expr{delim, items}}
		}
		var t Template
		for i, p := range parts {
			if i > 0 && delim != "" {
				t = append(t, delim)
			}
			t = append(t, p)
		}
		return simplify(t)
	case "Fn::Select":
		list, _ := arg.([]any)
		if len(list) != 2 {
			c.fail("%s: Fn::Select needs [index, list]", where)
			return nil
		}
		idx := c.value(list[0], where)
		items := c.value(list[1], where)
		if arr, ok := items.([]Expr); ok {
			if i, err := strconv.Atoi(fmt.Sprint(idx)); err == nil && i >= 0 && i < len(arr) {
				return arr[i]
			}
		}
		return Call{"element", []Expr{items, idx}}
	case "Fn::Split":
		list, _ := arg.([]any)
		if len(list) != 2 {
			c.fail("%s: Fn::Split needs [delimiter, string]", where)
			return nil
		}
		return Call{"split", []Expr{c.value(list[0], where), c.value(list[1], where)}}
	case "Fn::Base64":
		return Call{"base64encode", []Expr{c.value(arg, where)}}
	case "Fn::If":
		list, _ := arg.([]any)
		if len(list) != 3 {
			c.fail("%s: Fn::If needs [condition, then, else]", where)
			return nil
		}
		name, _ := list[0].(string)
		b, ok := c.conds[name]
		if !ok {
			c.fail("%s: unknown condition %s", where, name)
			return nil
		}
		if b {
			return c.value(list[1], where)
		}
		return c.value(list[2], where)
	case "Fn::FindInMap":
		v, err := c.findInMap(arg, nil)
		if err != nil {
			c.fail("%s: %v", where, err)
			return nil
		}
		return c.value(v, where)
	}
	c.fail("%s: %s is not supported (resolve it in the stack first)", where, fn)
	return nil
}

func simplify(t Template) Expr {
	if len(t) == 0 {
		return ""
	}
	all := true
	var b strings.Builder
	for _, p := range t {
		s, ok := p.(string)
		if !ok {
			all = false
			break
		}
		b.WriteString(s)
	}
	if all {
		return b.String()
	}
	return t
}

func (c *conv) refExpr(name, where string) Expr {
	switch name {
	case "AWS::Region":
		c.data["region"] = true
		return Raw("data.aws_region.current.name")
	case "AWS::AccountId":
		c.data["caller"] = true
		return Raw("data.aws_caller_identity.current.account_id")
	case "AWS::Partition":
		c.data["partition"] = true
		return Raw("data.aws_partition.current.partition")
	case "AWS::URLSuffix":
		c.data["partition"] = true
		return Raw("data.aws_partition.current.dns_suffix")
	case "AWS::StackName":
		return c.in.StackName
	case "AWS::NoValue":
		return noValue{}
	case "AWS::StackId", "AWS::NotificationARNs":
		c.fail("%s: %s has no meaning once the stack is gone", where, name)
		return nil
	}
	if v, ok := c.vars[name]; ok {
		return Raw("var." + v)
	}
	r, ok := c.refs[name]
	if !ok {
		c.fail("%s: Ref %s points at nothing that is being converted", where, name)
		return nil
	}
	if r.ref == "" {
		c.fail("%s: Ref of %s is not supported", where, name)
		return nil
	}
	return Raw(r.addr + "." + r.ref)
}

func (c *conv) getAttExpr(res, attr, where string) Expr {
	r, ok := c.refs[res]
	if !ok {
		c.fail("%s: GetAtt %s.%s points at nothing that is being converted", where, res, attr)
		return nil
	}
	a, ok := r.getAtt[attr]
	if !ok {
		c.fail("%s: GetAtt %s.%s is not supported", where, res, attr)
		return nil
	}
	// "arn|:*" means the attribute followed by a literal suffix (CloudFormation's value differs).
	if attrName, suffix, ok := strings.Cut(a, "|"); ok {
		return Template{Raw(r.addr + "." + attrName), suffix}
	}
	return Raw(r.addr + "." + a)
}

// staticID resolves an import ID.
func (c *conv) staticID(v any, where string) string {
	s, err := c.static(v, nil)
	if err != nil {
		c.fail("%s: import ID cannot be worked out: %v", where, err)
		return ""
	}
	return fmt.Sprint(s)
}

// ---- variables, outputs, versions ----

func (c *conv) variables() string {
	var blocks []*Block
	for _, name := range c.in.Template.ParamOrder {
		p := c.in.Template.Parameters[name]
		b := &Block{Type: "variable", Labels: []string{c.vars[name]}}
		typ := "string"
		switch {
		case p.Type == "Number":
			typ = "number"
		case strings.HasPrefix(p.Type, "List<") || p.Type == "CommaDelimitedList":
			typ = "list(string)"
		}
		b.Set("type", Raw(typ))
		if p.Description != "" {
			b.Set("description", p.Description)
		}
		if p.NoEcho {
			b.Set("sensitive", true)
		} else if v, ok := c.paramValue(name); ok {
			switch typ {
			case "number":
				if f, err := strconv.ParseFloat(fmt.Sprint(v), 64); err == nil {
					b.Set("default", f)
				}
			case "list(string)":
				b.Set("default", c.value(v, "parameter "+name))
			default:
				b.Set("default", fmt.Sprint(v))
			}
		}
		blocks = append(blocks, b)
	}
	if c.data["region"] {
		blocks = append(blocks, &Block{Type: "data", Labels: []string{"aws_region", "current"}})
	}
	if c.data["caller"] {
		blocks = append(blocks, &Block{Type: "data", Labels: []string{"aws_caller_identity", "current"}})
	}
	if c.data["partition"] {
		blocks = append(blocks, &Block{Type: "data", Labels: []string{"aws_partition", "current"}})
	}
	return "# Parameters of the stack, defaulting to the values it was deployed with.\n\n" + Render(blocks)
}

func (c *conv) outputs() []*Block {
	var out []*Block
	for _, o := range c.in.Template.Outputs {
		if o.Condition != "" && !c.conds[o.Condition] {
			continue
		}
		b := &Block{Type: "output", Labels: []string{snake(o.Name)}}
		b.Set("value", c.value(o.Value, "output "+o.Name))
		if o.Description != "" {
			b.Set("description", o.Description)
		}
		out = append(out, b)
	}
	return out
}

